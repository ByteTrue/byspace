const { withAppBuildGradle } = require("expo/config-plugins");

const GENERATED_MARKER = "// @generated by with-android-release-signing";

function applyAndroidReleaseSigningGradle(source) {
  if (source.includes(GENERATED_MARKER)) return source;

  const androidMarker = "\nandroid {\n";
  const androidIndex = source.indexOf(androidMarker);
  if (androidIndex === -1) {
    throw new Error("Could not configure Android release signing without an android block");
  }

  const variables = `
${GENERATED_MARKER}
def byspaceAndroidKeystorePath = System.getenv("BYSPACE_ANDROID_KEYSTORE_PATH")
def byspaceAndroidKeystorePassword = System.getenv("BYSPACE_ANDROID_KEYSTORE_PASSWORD")
def byspaceAndroidKeyAlias = System.getenv("BYSPACE_ANDROID_KEY_ALIAS")
def byspaceAndroidKeyPassword = System.getenv("BYSPACE_ANDROID_KEY_PASSWORD")
def byspaceAndroidReleaseSigningConfigured = [
    byspaceAndroidKeystorePath,
    byspaceAndroidKeystorePassword,
    byspaceAndroidKeyAlias,
    byspaceAndroidKeyPassword,
].every { value -> value != null && !value.isEmpty() }
def byspaceAndroidReleaseSigningRequired = System.getenv("BYSPACE_REQUIRE_RELEASE_SIGNING") == "1"
if (byspaceAndroidReleaseSigningRequired && !byspaceAndroidReleaseSigningConfigured) {
    throw new GradleException("BySpace release signing is required but Android signing credentials are incomplete")
}
`;
  let output = `${source.slice(0, androidIndex)}${variables}${source.slice(androidIndex)}`;

  const signingStart = output.indexOf("    signingConfigs {");
  const signingBoundary = "    }\n    buildTypes {";
  const signingEnd = output.indexOf(signingBoundary, signingStart);
  if (signingStart === -1 || signingEnd === -1) {
    throw new Error("Could not configure Android release signing without signingConfigs");
  }
  const releaseSigningConfig = `        release {
            if (byspaceAndroidReleaseSigningConfigured) {
                storeFile file(byspaceAndroidKeystorePath)
                storePassword byspaceAndroidKeystorePassword
                keyAlias byspaceAndroidKeyAlias
                keyPassword byspaceAndroidKeyPassword
            }
        }
`;
  output = `${output.slice(0, signingEnd)}${releaseSigningConfig}${output.slice(signingEnd)}`;

  const releaseStart = output.indexOf(
    "        release {",
    signingEnd + releaseSigningConfig.length,
  );
  const releaseSigningLine = "            signingConfig signingConfigs.debug";
  const releaseSigningIndex = output.indexOf(releaseSigningLine, releaseStart);
  if (releaseStart === -1 || releaseSigningIndex === -1) {
    throw new Error("Could not replace the generated debug release signing configuration");
  }
  const replacement =
    "            signingConfig byspaceAndroidReleaseSigningConfigured ? signingConfigs.release : signingConfigs.debug";
  return `${output.slice(0, releaseSigningIndex)}${replacement}${output.slice(releaseSigningIndex + releaseSigningLine.length)}`;
}

function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (modConfig) => {
    if (modConfig.modResults.language !== "groovy") {
      throw new Error("BySpace Android release signing requires a Groovy app build.gradle");
    }
    modConfig.modResults.contents = applyAndroidReleaseSigningGradle(modConfig.modResults.contents);
    return modConfig;
  });
}

withAndroidReleaseSigning.applyAndroidReleaseSigningGradle = applyAndroidReleaseSigningGradle;

module.exports = withAndroidReleaseSigning;
